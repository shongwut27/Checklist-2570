export function getCabinetId(deptName: string): string {
  if (!deptName) return "N/A";
  const trimmed = deptName.trim();
  if (CABINET_MAP[trimmed]) return CABINET_MAP[trimmed];

  const lines = trimmed.split("\n").map((s) => s.trim());
  if (lines[0] && CABINET_MAP[lines[0]]) return CABINET_MAP[lines[0]];

  const match = trimmed.match(/^([\u0E00-\u0E7F0-9\s()/\-.,]+?)([A-Za-z].*)?$/);
  if (match && match[1]) {
    const thaiPart = match[1].trim();
    if (CABINET_MAP[thaiPart]) return CABINET_MAP[thaiPart];
  }

  for (const key in CABINET_MAP) {
    if (trimmed.includes(key) || key.includes(trimmed)) {
      return CABINET_MAP[key];
    }
  }

  return "N/A";
}

